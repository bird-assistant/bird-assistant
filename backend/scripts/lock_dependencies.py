#!/usr/bin/env python3
"""Resolve hash-locked dependencies from pyproject.toml using real pip artifacts.

Run from backend/: python scripts/lock_dependencies.py --profile dev
Install: python -m pip install --require-hashes -r requirements-dev-lock.txt
Then: python -m pip install --no-deps --no-build-isolation -e .

GPU locks must be generated ON the validated CUDA host, with all dependency
wheels (including the exact CUDA torch/torchvision wheels) in --wheelhouse.
No GPU dependency downloads or guessed versions are performed by this script.
Archive that wheelhouse and the image digest/driver alongside the generated lock.
Restore with --no-index --find-links /path/to/wheelhouse --require-hashes.
Locks are specific to the generating Python minor, OS and architecture.
The cpu-test profile adds requirements-cpu-test.txt for offline model/tracker
compatibility tests with CPU torch wheels. It is not a GPU deployment lock.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import platform
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CPU_WHEEL_LINKS = [
    "https://download.pytorch.org/whl/cpu/torch/",
    "https://download.pytorch.org/whl/cpu/torchvision/",
]


def render_lock(report: dict[str, Any], profile: str, pip_version: str, input_digest: str) -> str:
    entries = []
    for item in report["install"]:
        metadata = item["metadata"]
        name, version = metadata["name"], metadata["version"]
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", name) or not re.fullmatch(
            r"[A-Za-z0-9][A-Za-z0-9.!+_-]*", version
        ):
            raise ValueError("unsafe package name or version in pip report")
        digest = item["download_info"].get("archive_info", {}).get("hashes", {}).get("sha256", "")
        if not re.fullmatch(r"[a-fA-F0-9]{64}", digest):
            raise ValueError(f"pip did not provide a wheel SHA-256 for {name}")
        if not item["download_info"]["url"].split("?", 1)[0].endswith(".whl"):
            raise ValueError(f"lock requires a wheel artifact: {name}")
        entries.append(f"{name}=={version} --hash=sha256:{digest}")
    if not entries:
        raise ValueError("resolver returned no dependencies")
    return "\n".join(
        [
            "# Generated by scripts/lock_dependencies.py from actual pip resolution; do not edit versions.",
            f"# Profile: {profile}; Python: {platform.python_version()}",
            f"# Target: {sys.platform}/{platform.machine()}/"
            f"cp{sys.version_info.major}{sys.version_info.minor}",
            f"# Dependency inputs SHA-256: {input_digest}",
            f"# Resolver pip: {pip_version}; one verified wheel hash per package for this platform.",
            "# Install with --require-hashes; install project with --no-deps --no-build-isolation.",
            *([f"--find-links {url}" for url in CPU_WHEEL_LINKS] if profile == "cpu-test" else []),
            *sorted(entries, key=str.casefold),
            "",
        ]
    )


def generate(profile: str, output: Path, wheelhouse: Path | None, *, check: bool = False) -> None:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    requirements = project["build-system"]["requires"] + project["project"]["dependencies"]
    if profile == "cpu-test":
        requirements += project["project"]["optional-dependencies"]["test"]
        requirements += project["project"]["optional-dependencies"]["gpu"]
    elif profile != "base":
        extra = "test" if profile == "dev" else "gpu"
        requirements += project["project"]["optional-dependencies"][extra]
    digest_material = json.dumps(requirements, separators=(",", ":")).encode()
    cpu_input = ROOT / "requirements-cpu-test.txt"
    if profile == "cpu-test":
        digest_material += b"\0" + cpu_input.read_bytes() + json.dumps(CPU_WHEEL_LINKS).encode()
    input_digest = hashlib.sha256(digest_material).hexdigest()
    if check:
        lines = output.read_text(encoding="utf-8").splitlines()
        expected = [
            f"# Profile: {profile}; Python: {platform.python_version()}",
            f"# Target: {sys.platform}/{platform.machine()}/"
            f"cp{sys.version_info.major}{sys.version_info.minor}",
            f"# Dependency inputs SHA-256: {input_digest}",
        ]
        if any(line not in lines for line in expected):
            raise ValueError("lock target or dependency inputs changed; regenerate on the target environment")
        print(f"Lock target and dependency inputs match: {output}")
        return
    pip_version = importlib.metadata.version("pip")
    with tempfile.TemporaryDirectory(prefix="bird-dependency-lock-") as temporary:
        report_path = Path(temporary) / "report.json"
        command = [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--ignore-installed",
            "--only-binary=:all:",
            "--report",
            str(report_path),
        ]
        if profile == "cpu-test":
            command += ["--requirement", str(cpu_input)]
            for url in CPU_WHEEL_LINKS:
                command += ["--find-links", url]
        if profile == "gpu":
            if wheelhouse is None or not wheelhouse.is_dir():
                raise ValueError(
                    "GPU lock requires --wheelhouse containing the validated environment's wheels"
                )
            import torch
            import torchvision

            if not torch.cuda.is_available() or torch.version.cuda is None:
                raise RuntimeError("GPU lock requires a working CUDA PyTorch environment")
            # Exercise the extension that YOLO uses, catching mismatched torch/vision builds.
            torchvision.ops.nms(
                torch.tensor([[0.0, 0.0, 1.0, 1.0]], device="cuda"), torch.ones(1, device="cuda"), 0.5
            )
            torch.cuda.synchronize()
            constraints = Path(temporary) / "installed.txt"
            names = {
                dist.metadata["Name"]
                for dist in importlib.metadata.distributions()
                if dist.metadata["Name"] and dist.metadata["Name"].casefold() != project["project"]["name"]
            }
            installed = {name: importlib.metadata.version(name) for name in names}
            constraints.write_text(
                "\n".join(f"{name}=={version}" for name, version in sorted(installed.items()))
            )
            command += [
                "--no-index",
                "--find-links",
                str(wheelhouse.resolve()),
                "--constraint",
                str(constraints),
            ]
        elif wheelhouse is not None:
            command += ["--no-index", "--find-links", str(wheelhouse.resolve())]
        subprocess.run([*command, *requirements], check=True, cwd=ROOT)
        report = json.loads(report_path.read_text(encoding="utf-8"))
        if profile == "gpu":
            for item in report["install"]:
                name, version = item["metadata"]["name"], item["metadata"]["version"]
                if importlib.metadata.version(name) != version:
                    raise RuntimeError(f"resolved {name} differs from installed validated environment")
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(render_lock(report, profile, pip_version, input_digest), encoding="utf-8")
        print(f"Generated {output}; validate installation in a fresh environment before release.")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--profile", choices=["base", "dev", "cpu-test", "gpu"], default="dev")
    parser.add_argument("--wheelhouse", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", action="store_true", help="check lock target/inputs without resolving")
    args = parser.parse_args()
    generate(
        args.profile,
        args.output or ROOT / f"requirements-{args.profile}-lock.txt",
        args.wheelhouse,
        check=args.check,
    )


if __name__ == "__main__":
    main()
